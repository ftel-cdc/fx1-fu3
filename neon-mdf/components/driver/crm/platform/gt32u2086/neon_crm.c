static uint32_t crm_enter_critical(void);
static void crm_exit_critical(uint32_t primask);

/*==================================================================================================
*                                        PRIVATE FUNCTIONS
==================================================================================================*/

static uint32_t crm_enter_critical(void) {
    uint32_t primask = __get_PRIMASK();
    __disable_irq();
    return primask;
}

static void crm_exit_critical(uint32_t primask) {
    __set_PRIMASK(primask);
}

