/*
 * GT32U2086 Backend CRM.
 *
 * The position and mask of the field are derived entirely from GT32U2086.h generated by GT32U2086.yaml; no repeats
 * of bits from the old LL driver. The public API does not know the register groups below.
 */

#define CRM_PLL_OD_MAX (CRM_PLL_OD_Msk >> CRM_PLL_OD_Pos)
#define CRM_PLL_M_DIV_MAX (CRM_PLL_M_DIV_Msk >> CRM_PLL_M_DIV_Pos)
#define CRM_PLL_N_DIV_MAX (CRM_PLL_N_DIV_Msk >> CRM_PLL_N_DIV_Pos)
#define CRM_PLL_LOCK_COUNT_MAX (CRM_PLL_CTRL_COUNT_Msk >> CRM_PLL_CTRL_COUNT_Pos)
#define CRM_CLOCK_DIVIDER_MAX (CRM_CLK_DIV_Msk >> CRM_CLK_DIV_Pos)

/*==================================================================================================
*                                  STRUCTURES AND OTHER TYPEDEFS
==================================================================================================*/
typedef enum {
    GT32U2086_CRM_CLOCK_REGISTER_NONE = 0,
    GT32U2086_CRM_CLOCK_REGISTER_GATE_0,
    GT32U2086_CRM_CLOCK_REGISTER_GATE_1,
} gt32u2086_crm_clock_register_t;

typedef enum {
    GT32U2086_CRM_RESET_REGISTER_NONE = 0,
    GT32U2086_CRM_RESET_REGISTER_GROUP_0,
    GT32U2086_CRM_RESET_REGISTER_GROUP_1,
    GT32U2086_CRM_RESET_REGISTER_GROUP_2,
} gt32u2086_crm_reset_register_t;

typedef struct {
    uint32_t clock_register;
    uint32_t reset_register;
    uint32_t clock_mask;
    uint32_t reset_mask;
} gt32u2086_crm_peripheral_map_t;

