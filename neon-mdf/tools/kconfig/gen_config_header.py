#!/usr/bin/env python3
"""gen_config_header.py - create sdkconfig.h + sdkconfig.cmake from Kconfig + sdkconfig file, use
kconfiglib (the library ESP-IDF/Zephyr is also used, do not write Kconfig parser from scratch).

Used (usually called from CMake, see cmake/kconfig.cmake):
  python3 gen_config_header.py --kconfig Kconfig --sdkconfig /path/to/sdkconfig \\
      --header-out build/config/sdkconfig.h --cmake-out build/config/sdkconfig.cmake

ESP-IDF identical naming convention: symbol in Kconfig has NO prefix (e.g. `NEON_MDF_HAL_UART`),
generated macro/variable automatically adds `CONFIG_` (e.g.
`CONFIG_NEON_MDF_HAL_UART`).
"""
import argparse
import os

import kconfiglib


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kconfig", required=True, help="Original Kconfig file (mainmenu)")
    ap.add_argument("--sdkconfig", required=True, help="File to save app selections - generate by default if not available")
    ap.add_argument("--header-out", required=True)
    ap.add_argument("--cmake-out", required=True)
    args = ap.parse_args()

    kconf = kconfiglib.Kconfig(args.kconfig)

    if os.path.isfile(args.sdkconfig):
        kconf.load_config(args.sdkconfig)

    os.makedirs(os.path.dirname(os.path.abspath(args.sdkconfig)), exist_ok=True)
    # Always rewrite sdkconfig (same as ESP-IDF): the new option will automatically fill default into the
    # file, the old option that no longer exists will be removed from the file.
    kconf.write_config(args.sdkconfig)

    os.makedirs(os.path.dirname(os.path.abspath(args.header_out)), exist_ok=True)
    os.makedirs(os.path.dirname(os.path.abspath(args.cmake_out)), exist_ok=True)

    header_lines = [
        "/* Auto-generated by neon-mdf/tools/kconfig/gen_config_header.py - DO NOT EDIT BY HAND. */",
        "#ifndef SDKCONFIG_H",
        "#define SDKCONFIG_H",
        "",
    ]
    cmake_lines = [
        "# Auto-generated by neon-mdf/tools/kconfig/gen_config_header.py - DO NOT EDIT BY HAND.",
        "",
    ]

    for sym in kconf.unique_defined_syms:
        name = f"CONFIG_{sym.name}"
        if sym.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
            if sym.str_value in ("y", "m"):
                header_lines.append(f"#define {name} 1")
                cmake_lines.append(f"set({name} ON)")
            else:
                cmake_lines.append(f"set({name} OFF)")
        elif sym.type == kconfiglib.STRING:
            header_lines.append(f'#define {name} "{sym.str_value}"')
            cmake_lines.append(f'set({name} "{sym.str_value}")')
        elif sym.type in (kconfiglib.INT, kconfiglib.HEX):
            header_lines.append(f"#define {name} {sym.str_value}")
            cmake_lines.append(f"set({name} {sym.str_value})")

    header_lines += ["", "#endif /* SDKCONFIG_H */"]

    with open(args.header_out, "w", encoding="utf-8") as f:
        f.write("\n".join(header_lines) + "\n")
    with open(args.cmake_out, "w", encoding="utf-8") as f:
        f.write("\n".join(cmake_lines) + "\n")

    # Track sourced Kconfig files as well as the top-level configuration.
    with open(os.path.join(os.path.dirname(os.path.abspath(args.cmake_out)), "kconfig_inputs.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(os.path.abspath(p) for p in kconf.kconfig_filenames) + "\n")

    print(f"sdkconfig: {args.sdkconfig}")
    print(f"sdkconfig.h: {args.header_out}")
    print(f"sdkconfig.cmake: {args.cmake_out}")


if __name__ == "__main__":
    main()
