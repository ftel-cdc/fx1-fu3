"""Sinh startup_<DEVICE>.s (GNU AS) cho Cortex-M — dùng chung cho MỌI core đã
xác nhận trong core_info.py (hiện: cortex-m0/cortex-m0plus ARMv6-M,
cortex-m3/cortex-m4 ARMv7-M).

16 entry đầu tiên của vector table CỐ ĐỊNH theo kiến trúc ARM (không đổi
giữa vendor), NHƯNG 4 slot (4/5/6/12) khác nhau thật giữa 2 họ:
  0:  Initial Main Stack Pointer (_estack, từ linker script)
  1:  Reset_Handler
  2:  NMI_Handler
  3:  HardFault_Handler
  4:  MemManage_Handler   — CHỈ core có has_extended_fault_handlers=True (ARMv7-M+/mainline); còn lại Reserved
  5:  BusFault_Handler    — như trên
  6:  UsageFault_Handler  — như trên
  7-10: Reserved (mọi core)
  11: SVC_Handler
  12: DebugMon_Handler    — như MemManage, chỉ ARMv7-M+/mainline
  13: Reserved
  14: PendSV_Handler
  15: SysTick_Handler
  16+: <NAME>_IRQHandler theo `interrupts` trong device .yaml — vị trí THẬT =
       16 + irq.number (không phải thứ tự liệt kê trong file YAML), khe
       trống (`number` bị bỏ qua giữa chừng) = Reserved (`.word 0`) — cùng
       cách gap-fill với backends/riscv/gen_startup.py, tránh lệch vector
       table nếu 1 device YAML tương lai không khai liên tục 0..N-1.

Bug đã fix (lịch sử, xem guide/ArchitectDetail.md nếu cần): bản cũ dùng 1
template layout ARMv6-M cố định cho MỌI core (kể cả Cortex-M4 WEACT_F412,
mpu_present=true) — entry 4/5/6/12 bị ghi `.word 0` (literal, KHÔNG PHẢI
Default_Handler) thay vì handler thật; đồng thời entry IRQ chỉ theo thứ tự
liệt kê trong YAML, không theo `number` — dễ lệch vector table nếu YAML có
khoảng trống không được điền RESERVED thủ công.
"""

from . import core_info


def _section(title):
    return [
        "/* ----------------------------------------------------------------------------",
        f" * {title}",
        " * ---------------------------------------------------------------------------- */",
    ]


def _directive(name, operand):
    return f"        {name:<12}{operand}"


def _vector(symbol, description, width):
    return f"        {'.word':<12}{symbol:<{width}} /* {description} */"


RESET_HANDLER = """        .section    .text.Reset_Handler,"ax",%progbits
        .balign     4
        .weak       Reset_Handler
        .type       Reset_Handler, %function
        .thumb_func
Reset_Handler:
        /* Set the initial stack pointer. */
        ldr         r0, =_estack
        mov         sp, r0

        /* Copy initialized data from Flash to RAM. */
        ldr         r0, =_sidata
        ldr         r1, =_sdata
        ldr         r2, =_edata
        movs        r3, #0
        b           LoopCopyDataInit

CopyDataInit:
        ldr         r4, [r0, r3]
        str         r4, [r1, r3]
        adds        r3, r3, #4

LoopCopyDataInit:
        adds        r4, r1, r3
        cmp         r4, r2
        bcc         CopyDataInit

        /* Clear the zero-initialized data in RAM. */
        ldr         r2, =_sbss
        b           LoopFillZerobss

FillZerobss:
        movs        r3, #0
        str         r3, [r2]
        adds        r2, r2, #4

LoopFillZerobss:
        ldr         r3, =_ebss
        cmp         r2, r3
        bcc         FillZerobss

        /* Initialize the system and enter the application. */
        bl          SystemInit
        bl          main
        bx          lr

        .size       Reset_Handler, .-Reset_Handler
        .ltorg
"""

DEFAULT_HANDLER = """        .section    .text.Default_Handler,"ax",%progbits
        .balign     2
        .type       Default_Handler, %function
        .thumb_func
Default_Handler:
Infinite_Loop:
        b           Infinite_Loop

        .size       Default_Handler, .-Default_Handler
"""


def generate(device, out_path: str):
    core = core_info.lookup(device.cpu.core)
    profile_arg = f" --profile {device.profile.name}" if device.profile.flash else ""
    lines = [
        "/* ============================================================================",
        f" * File        : startup_{device.device}.s",
        f" * Device      : {device.device} ({device.cpu.core})",
        " * Toolchain   : GNU assembler (arm-none-eabi)",
        " * Description : Vector table and reset startup.",
        " *               - Set the initial stack pointer.",
        " *               - Copy .data and clear .bss.",
        " *               - Call SystemInit, then main.",
        " *               - Provide weak default exception and interrupt handlers.",
        " *",
        " * Auto-generated by mcu-description/tools/generate.py - DO NOT EDIT BY HAND.",
        f" * Source      : mcu-description/devices/{device.device}.yaml",
        f" * Regenerate  : python3 mcu-description/tools/generate.py --device {device.device}{profile_arg}",
        " * ============================================================================ */",
        "",
    ]
    lines += _section("Assembler configuration")
    lines += [
        _directive(".syntax", "unified"),
        _directive(".cpu", device.cpu.core),
        _directive(".fpu", "softvfp"),
        "        .thumb",
        "",
    ]
    lines += _section("External symbols and public entry points")
    lines.append("        /* Memory boundaries supplied by the linker script. */")
    for name in ("_estack", "_sidata", "_sdata", "_edata", "_sbss", "_ebss"):
        lines.append(_directive(".extern", name))
    lines += ["", "        /* Application and system initialization. */"]
    for name in ("SystemInit", "main"):
        lines.append(_directive(".extern", name))
    lines.append("")
    for name in ("g_pfnVectors", "Default_Handler"):
        lines.append(_directive(".global", name))
    lines.append("")

    # Slot numbers are architectural, independent of declaration order in YAML.
    core_vectors = [
        ("_estack", "Initial stack pointer"),
        ("Reset_Handler", "Reset"),
        ("NMI_Handler", "Non-maskable interrupt"),
        ("HardFault_Handler", "Hard fault"),
    ]
    if core.has_extended_fault_handlers:
        core_vectors += [
            ("MemManage_Handler", "Memory management fault"),
            ("BusFault_Handler", "Bus fault"),
            ("UsageFault_Handler", "Usage fault"),
        ]
    else:
        core_vectors += [("0", "Reserved")] * 3
    core_vectors += [("0", "Reserved")] * 4
    core_vectors.append(("SVC_Handler", "Supervisor call"))
    core_vectors.append(("DebugMon_Handler", "Debug monitor") if core.has_extended_fault_handlers
                        else ("0", "Reserved"))
    core_vectors += [("0", "Reserved"), ("PendSV_Handler", "Pendable service"),
                     ("SysTick_Handler", "System tick")]

    interrupts = {irq.number: irq for irq in device.interrupts}
    external_vectors = []
    for number in range(max(interrupts, default=-1) + 1):
        irq = interrupts.get(number)
        if irq is None:
            external_vectors.append(("0", f"IRQ{number}: Reserved"))
        else:
            description = " ".join(irq.description.split()) or irq.name
            external_vectors.append((f"{irq.name}_IRQHandler", f"IRQ{number}: {description}"))
    width = max(32, max(len(symbol) for symbol, _ in core_vectors + external_vectors))

    lines += _section("Vector table - placed by the linker in .isr_vector")
    lines += [
        _directive(".section", '.isr_vector,"a",%progbits'),
        _directive(".balign", "4"),
        _directive(".type", "g_pfnVectors, %object"),
        "",
        "g_pfnVectors:",
        "        /* Core exceptions */",
    ]
    lines += [_vector(symbol, description, width) for symbol, description in core_vectors]
    lines += ["", "        /* External interrupts */"]
    lines += [_vector(symbol, description, width) for symbol, description in external_vectors]
    lines += ["", _directive(".size", "g_pfnVectors, .-g_pfnVectors"), ""]

    lines += _section("Reset handler")
    lines += [RESET_HANDLER.rstrip(), ""]
    lines += _section("Default handler - stop here for an unhandled interrupt")
    lines += [DEFAULT_HANDLER.rstrip(), ""]
    lines += _section("Weak handler aliases - override with a handler of the same name")
    core_handlers = [symbol for symbol, _ in core_vectors[2:] if symbol != "0"]
    external_handlers = [symbol for symbol, _ in external_vectors if symbol != "0"]
    for title, group in (("Core exception handlers", core_handlers),
                         ("Peripheral interrupt handlers (IRQ order)", external_handlers)):
        lines.append(f"        /* {title} */")
        for symbol in group:
            lines += [_directive(".weak", symbol),
                      _directive(".thumb_set", f"{symbol}, Default_Handler"), ""]
    lines.append("/* End of file */")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
