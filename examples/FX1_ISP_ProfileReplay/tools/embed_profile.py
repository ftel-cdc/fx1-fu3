"""Rebuild the embedded CSR stream from this example's local profile snapshot."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
header = root / 'Reference/fx1_isp/fx1_isp_csr.h'
offsets = {n: int(v, 16) for n, v in re.findall(
    r'#define\s+FX1_ISP_(\w+)_OFFSET\s+(0x[0-9a-fA-F]+)[uU]?\b', header.read_text())}
pairs = []
for line in (root / 'Src/d65_full_profile.csrw').read_text().splitlines():
    fields = line.split('#', 1)[0].split()
    if fields:
        name, value = fields
        pairs.append((offsets[name], int(value, 0)))
assert len(pairs) == 1128, 'Update the job contract if the profile length changes'
text = '/* Generated by tools/embed_profile.py; ordered writes must remain ordered. */\n'
text += 'static const fx1_isp_reg_write profile[] = {\n'
text += ''.join(f'    {{0x{x:08x}u, 0x{y:08x}u}},\n' for x, y in pairs)
text += '''};
static const isp_demo_job job = {
    .magic = ISP_DEMO_JOB_MAGIC, .version = ISP_DEMO_VERSION,
    .width = 2688, .height = 1520, .bayer = 3,
    .in_addr = 0x81000000, .in_stride = 5376,
    .y_addr = 0x88000000, .uv_addr = 0x88400000, .out_stride = 2688,
    .profile_count = sizeof profile / sizeof profile[0], .frames = 2,
    .mode = ISP_DEMO_MODE_PROFILE, .outputs = 1, .profile_id = 1
};
'''
(root / 'Src/profile_data.h').write_text(text)
print(f'Embedded {len(pairs)} writes; no external profile or VP required at build time')
